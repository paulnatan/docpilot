function getLang() {
  return localStorage.getItem("docpilot_lang") || "it";
}

function setLang(lang) {
  localStorage.setItem("docpilot_lang", lang);
  // Applica senza reload — ogni pagina ha la sua funzione applyLang
  if (typeof applyLandingLang === "function") applyLandingLang();
  if (typeof applyTranslations === "function") applyTranslations();
  // Chiudi il menu
  const menu = document.getElementById("lang-menu");
  if (menu) menu.style.display = "none";
}

// Eseguito automaticamente su ogni pageshow (anche quando si torna col browser)
window.addEventListener("pageshow", () => {
  if (typeof applyLandingLang === "function") applyLandingLang();
  if (typeof applyTranslations === "function") applyTranslations();
});

function t(key) {
  const lang = getLang();
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS["it"][key] || key;
}

